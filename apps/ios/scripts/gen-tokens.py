#!/usr/bin/env python3
"""Print DesignSystem/Sources/DesignSystem/Tokens.swift from docs/design/tokens.json.

The design tokens are the source (docs/design/README.md §8); this keeps the Swift copy honest. `make lint-ios` runs it
and fails when the committed file differs, so a token change comes with its regenerated Swift.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
TOKENS = ROOT / "docs/design/tokens.json"

# Each type step scales with the user's text size through the system text style it is closest to.
RELATIVE_TO = {
    "largeTitle": "largeTitle",
    "title1": "title",
    "title2": "title2",
    "bodyStrong": "body",
    "body": "body",
    "secondary": "subheadline",
    "caption": "footnote",
    "micro": "caption2",
}
SPACE_NAMES = ["xxs", "xs", "s", "m", "l", "xl", "xxl", "xxxl"]
# Nested token groups become nested enums; these names would shadow a framework type at the use site.
TYPE_NAMES = {"calendar": "Grid"}


def type_name(key):
    return TYPE_NAMES.get(key, key[0].upper() + key[1:])


def number(value):
    return ("%g" % value) if isinstance(value, float) else str(value)


def has_numbers(group):
    for value in group.values():
        if isinstance(value, dict) and has_numbers(value):
            return True
        if isinstance(value, (int, float)) and not isinstance(value, bool):
            return True
        if isinstance(value, list) and value and all(isinstance(v, (int, float)) for v in value):
            return True
    return False


def rgba(value):
    """`#rrggbb` or `rgba(r,g,b,a)` as (hex, alpha)."""
    if value.startswith("#"):
        return hex_(value), 1
    r, g, b, a = [part.strip() for part in value[value.index("(") + 1:value.index(")")].split(",")]
    return "0x%02x%02x%02x" % (int(r), int(g), int(b)), float(a)


def color(light, dark):
    (lh, la), (dh, da) = rgba(light), rgba(dark)
    if la == 1 and da == 1:
        return "Color(light: %s, dark: %s)" % (lh, dh)
    return "Color(light: %s, dark: %s, lightOpacity: %s, darkOpacity: %s)" % (lh, dh, number(la), number(da))


def emit_numbers(w, name, group, indent):
    """Emit the numeric leaves of a token group as a nested enum. Durations in milliseconds become seconds, so a view
    passes them to an animation as they are; colors and shadow strings are emitted with the colors instead."""
    if not has_numbers(group):
        return
    pad = "    " * indent
    w("%spublic enum %s {" % (pad, type_name(name)))
    for key, value in group.items():
        if isinstance(value, dict):
            emit_numbers(w, key, value, indent + 1)
        elif isinstance(value, bool) or isinstance(value, str):
            continue
        elif isinstance(value, list):
            if all(isinstance(v, (int, float)) and not isinstance(v, bool) for v in value):
                w("%s    public static let %s: [CGFloat] = [%s]" % (pad, key, ", ".join(number(v) for v in value)))
        elif key == "ms" or key.endswith("Ms"):
            label = "duration" if key in ("ms", "durationMs") else key[:-2] + "Duration"
            w("%s    public static let %s: TimeInterval = %s" % (pad, label, number(value / 1000)))
        else:
            w("%s    public static let %s: CGFloat = %s" % (pad, key, number(value)))
    w("%s}" % pad)


def hex_(value):
    return "0x" + value[1:].lower()


def main():
    tokens = json.loads(TOKENS.read_text())
    out = []
    w = out.append
    w("// Generated by apps/ios/scripts/gen-tokens.py from docs/design/tokens.json (design system v%s, %s)."
      % (tokens["meta"]["version"], tokens["meta"]["updated"]))
    w("// Edit the tokens and regenerate instead of this file; `make lint-ios` fails when the two differ.")
    w("")
    w("import SwiftUI")
    w("")
    w("/// Neutral colors, one value per appearance (docs/design/README.md §2.1).")
    w("public enum GeunalColor {")
    light, dark = tokens["color"]["light"], tokens["color"]["dark"]
    for key in light:
        w("    public static let %s = Color(light: %s, dark: %s)" % (key, hex_(light[key]), hex_(dark[key])))
    brand = tokens["color"]["brand"]
    w("")
    w("    /// Brand purple: the app icon, the brand surface and the selected tab (docs/design/README.md §2.3).")
    w("    public static let grape = Color(light: %s, dark: %s)" % (hex_(brand["grape"]), hex_(brand["grape"])))
    w("    public static let tabText = Color(light: %s, dark: %s)"
      % (hex_(brand["tabText"]["light"]), hex_(brand["tabText"]["dark"])))
    nav = tokens["nav"]
    w("")
    w("    /// Navigation and sheet chrome (docs/design/README.md §5, components.md §6–7).")
    pill, inactive = nav["tabBar"]["activePill"], nav["tabBar"]["inactive"]
    w("    public static let tabActivePill = %s" % color(pill["light"], pill["dark"]))
    w("    public static let tabInactive = %s" % color(inactive["light"], inactive["dark"]))
    badge = nav["badge"]
    for part in ("fill", "text", "ring"):
        w("    public static let badge%s = %s" % (part.capitalize(), color(badge["light"][part], badge["dark"][part])))
    sheet = tokens["sheet"]
    w("    public static let grabber = %s" % color(sheet["grabber"]["color"], sheet["grabber"]["color"]))
    w("    public static let scrim = %s" % color(sheet["scrim"], sheet["scrim"]))
    w("}")
    w("")
    w("/// The twelve group colors (docs/design/README.md §2.2). Each has five tints: the free-count scale in the group")
    w("/// calendar, where tint 5 is also the group's representative color and is the same in both appearances.")
    w("public enum GroupColor: String, CaseIterable, Sendable {")
    groups = tokens["color"]["group"]
    for key in groups:
        w("    case %s" % key)
    w("")
    w("    /// The Korean name the group settings show.")
    w("    public var name: String {")
    w("        switch self {")
    for key, group in groups.items():
        w('        case .%s: "%s"' % (key, group["name"]))
    w("        }")
    w("    }")
    w("")
    w("    /// The tint for a level from 1 to 5. Level 0 is the empty cell, `GeunalColor.emptyCell`.")
    w("    public func tint(_ level: Int) -> Color {")
    w('        precondition((1...5).contains(level), "tint levels run from 1 to 5")')
    w("        let ramp = Self.ramps[self]!")
    w("        return Color(light: ramp[level - 1].light, dark: ramp[level - 1].dark)")
    w("    }")
    w("")
    w("    /// The representative color: tint 5, with white text above 4.6:1.")
    w("    public var representative: Color { tint(5) }")
    w("")
    w("    /// Maps how many of a group's `total` members are free to a tint level (docs/design/tokens.json `freeCount`):")
    w("    /// nobody is the empty cell (0), everybody is 5, and the rest spread over 1 to 4.")
    w("    public static func level(free: Int, of total: Int) -> Int {")
    w('        precondition(total >= 1 && (0...total).contains(free), "free must be between 0 and total")')
    w("        if free == 0 { return 0 }")
    w("        if free == total { return 5 }")
    w("        return min(4, 1 + (free - 1) * 4 / (total - 1))")
    w("    }")
    w("")
    w("    private static let ramps: [GroupColor: [(light: UInt32, dark: UInt32)]] = [")
    for key, group in groups.items():
        w("        .%s: [" % key)
        for light_tint, dark_tint in zip(group["light"], group["dark"]):
            w("            (light: %s, dark: %s)," % (hex_(light_tint), hex_(dark_tint)))
        w("        ],")
    w("    ]")
    w("}")
    w("")
    w("extension Color {")
    w("    /// A color from two sRGB hex values, picked by the current appearance.")
    w("    public init(light: UInt32, dark: UInt32, lightOpacity: CGFloat = 1, darkOpacity: CGFloat = 1) {")
    w("        self.init(")
    w("            uiColor: UIColor { traits in")
    w("                traits.userInterfaceStyle == .dark")
    w("                    ? UIColor(rgb: dark, alpha: darkOpacity) : UIColor(rgb: light, alpha: lightOpacity)")
    w("            })")
    w("    }")
    w("}")
    w("")
    w("extension UIColor {")
    w("    fileprivate convenience init(rgb: UInt32, alpha: CGFloat) {")
    w("        self.init(")
    w("            red: CGFloat((rgb >> 16) & 0xFF) / 255,")
    w("            green: CGFloat((rgb >> 8) & 0xFF) / 255,")
    w("            blue: CGFloat(rgb & 0xFF) / 255,")
    w("            alpha: alpha)")
    w("    }")
    w("}")
    w("")
    w("/// The type scale (docs/design/README.md §3). Pretendard comes with M1; until then the system font carries the")
    w("/// sizes and weights, scaled with the user's text size through the text style each step is relative to.")
    w("public struct TypeStyle: Sendable, Hashable {")
    w("    public enum Weight: Sendable, Hashable {")
    w("        case regular")
    w("        case semibold")
    w("")
    w("        public var font: Font.Weight {")
    w("            switch self {")
    w("            case .regular: .regular")
    w("            case .semibold: .semibold")
    w("            }")
    w("        }")
    w("    }")
    w("")
    w("    public enum Relative: Sendable, Hashable {")
    for style in sorted(set(RELATIVE_TO.values()), key=list(RELATIVE_TO.values()).index):
        w("        case %s" % style)
    w("")
    w("        public var textStyle: Font.TextStyle {")
    w("            switch self {")
    for style in sorted(set(RELATIVE_TO.values()), key=list(RELATIVE_TO.values()).index):
        w("            case .%s: .%s" % (style, style))
    w("            }")
    w("        }")
    w("    }")
    w("")
    w("    public let size: CGFloat")
    w("    public let weight: Weight")
    w("    /// Letter spacing as a fraction of the size.")
    w("    public let tracking: CGFloat")
    w("    public let relativeTo: Relative")
    w("")
    for key, step in tokens["type"].items():
        weight = ".semibold" if step["weight"] == 600 else ".regular"
        w("    public static let %s = TypeStyle(size: %d, weight: %s, tracking: %s, relativeTo: .%s)"
          % (key, step["size"], weight, step["tracking"], RELATIVE_TO[key]))
    w("}")
    w("")
    w("/// Spacing steps, multiples of four (docs/design/README.md §4). Screen edges use 16 to 20.")
    w("public enum Space {")
    for name, value in zip(SPACE_NAMES, tokens["space"]):
        w("    public static let %s: CGFloat = %d" % (name, value))
    w("}")
    w("")
    w("/// Corner radii (docs/design/README.md §4).")
    w("public enum Radius {")
    for key, value in tokens["radius"].items():
        w("    public static let %s: CGFloat = %d" % (key, value))
    w("}")
    w("")
    w("/// Component sizes (docs/design/components.md), navigation and sheet metrics (docs/design/README.md §5).")
    w("public enum Metrics {")
    for key, value in tokens["component"].items():
        emit_numbers(w, key, value, 1)
    emit_numbers(w, "tabBar", tokens["nav"]["tabBar"], 1)
    emit_numbers(w, "nextUpBar", tokens["nav"]["nextUpBar"], 1)
    emit_numbers(w, "badge", tokens["nav"]["badge"], 1)
    w("    public static let minHitTarget: CGFloat = %s" % number(tokens["a11y"]["minHitTarget"]))
    w("}")
    w("")
    w("/// Motion (docs/design/components.md §9). With Reduce Motion on, views fade for `ReducedMotion.fadeDuration`")
    w("/// instead of sliding or springing.")
    w("public enum Motion {")
    for key, value in tokens["motion"].items():
        emit_numbers(w, key, value, 1)
    w("}")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
